import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Reuse the checked-in web assets, including their original viewBoxes.
const source = new URL('../../web/src/assets/icons/', import.meta.url);
const destination = new URL('../assets/meta/', import.meta.url);
mkdirSync(destination, { recursive: true });
const files = {
  home: 'home', menu: 'menu', notifications: 'notifications', bell: 'notifications',
  messenger: 'messages', friends: 'friends', users: 'groups', store: 'marketplace',
  reels: 'cr-reel', video: 'video', like: 'rl-like', comment: 'rl-comment',
  share: 'rl-share', more: 'rl-more', profile: 'rl-profile',
  'user-plus': 'fr-requests', 'friend-add': 'fr-requests', flag: 'cr-page',
};
const xml = Object.fromEntries([...new Set(Object.values(files))].map((name) => [name,
  readFileSync(new URL(`${name}.svg`, source), 'utf8').trim()]));
const aliases = Object.fromEntries(Object.entries(files).flatMap(([name, file]) => [[name, file], [`${name}-filled`, file]]));
writeFileSync(new URL('../components/ui/metaIcons.ts', import.meta.url),
  '// Generated by scripts/sync-meta-icons.mjs from frontend/web. Do not edit by hand.\n' +
  `const svg: Record<string, string> = ${JSON.stringify(xml, null, 2)};\n` +
  `const aliases: Record<string, string> = ${JSON.stringify(aliases, null, 2)};\n` +
  'export const metaIcon = (name: string): string | undefined => svg[aliases[name]];\n');
copyFileSync(new URL('../../web/public/fb/sidebar.webp', import.meta.url), new URL('sidebar.webp', destination));
console.log(`Synced ${Object.keys(xml).length} Meta SVGs and the sidebar sprite to ${fileURLToPath(destination)}`);
